#!/bin/sh
# Usage: mkunfold.sh <certificate.v> <name>
# Writes <name>_unfold.v next to the certificate: an Ltac `unfold_<name>`
# that unfolds exactly the definitions of the Gappa certificate <name> (and
# Gappa's interval predicates and float constants), leaving the real
# operations, the roundings and the powers of two folded. The certificate's
# definition names depend on the Gappa version, hence this generated helper.
set -eu
cert=$1; name=$2; dir=$(dirname "$cert")
names=$(sed -n 's/^Definition \([A-Za-z0-9_]*\) .*/XP.'"$name"'.\1/p' "$cert" | tr '\n' ' ')
cat > "$dir/${name}_unfold.v" <<EOT
(* Generated by tools/mkunfold.sh from the Gappa certificate $name.v. *)
From Flocq Require Core.
From Gappa Require Gappa_definitions Gappa_pred_bnd Gappa_round_def.
Require XP.$name.
Ltac unfold_$name :=
  cbv beta iota zeta delta [$names
    Gappa.Gappa_definitions.BND Gappa.Gappa_definitions.ABS Gappa.Gappa_definitions.REL
    Gappa.Gappa_definitions.float2R Flocq.Core.Defs.F2R Gappa.Gappa_pred_bnd.Float1
    Gappa.Gappa_definitions.lower Gappa.Gappa_definitions.upper
    Gappa.Gappa_definitions.Fnum Gappa.Gappa_definitions.Fexp Flocq.Core.Defs.Fnum Flocq.Core.Defs.Fexp];
  change Gappa.Gappa_round_def.rndNE with Flocq.Core.Round_NE.ZnearestE.
Ltac unfold_${name}_in H :=
  cbv beta iota zeta delta [$names
    Gappa.Gappa_definitions.BND Gappa.Gappa_definitions.ABS Gappa.Gappa_definitions.REL
    Gappa.Gappa_definitions.float2R Flocq.Core.Defs.F2R Gappa.Gappa_pred_bnd.Float1
    Gappa.Gappa_definitions.lower Gappa.Gappa_definitions.upper
    Gappa.Gappa_definitions.Fnum Gappa.Gappa_definitions.Fexp Flocq.Core.Defs.Fnum Flocq.Core.Defs.Fexp] in H;
  change Gappa.Gappa_round_def.rndNE with Flocq.Core.Round_NE.ZnearestE in H.
EOT
