// L2.2b: `DdDense` against the generic kernel (Chapter 11.7, invariant X1)
// ---------------------------------------------------------------------

type Dd = DoubleDouble;

/// The bits of a block.
fn bits(a: &DenseBlock<Dd>) -> Vec<(u64, u64)> {
    a.data
        .iter()
        .map(|v| (v.hi().to_bits(), v.lo().to_bits()))
        .collect()
}

/// A block of double-doubles with full 106-bit significands.
fn dd_block(rows: usize, cols: usize, rng: &mut Lcg) -> DenseBlock<Dd> {
    let data = (0..rows * cols)
        .map(|_| Dd::from_f64(rng.unit()) / (3.0 + rng.unit()))
        .collect();
    DenseBlock { rows, cols, data }
}

/// A lower triangular block with a diagonal away from zero (the strict
/// upper triangle holds values that no kernel may read or write).
fn dd_lower(n: usize, rng: &mut Lcg) -> DenseBlock<Dd> {
    let mut l = dd_block(n, n, rng);
    for j in 0..n {
        l.set(j, j, Dd::from_f64(2.0 + rng.unit()) / 3.0);
    }
    l
}

/// Every operation of `DdDense` leaves the bits `NaiveDense` leaves, on
/// shapes below, at and above the lanes and the cache blocks.
#[test]
fn dd_dense_returns_the_bits_of_naive_dense() {
    let mut rng = Lcg(0x11b2);
    for (m, k, n) in [
        (1, 1, 1),
        (3, 2, 2),
        (4, 4, 4),
        (7, 5, 3),
        (33, 9, 6),
        (70, 12, 5),
        (140, 70, 3),
        (261, 3, 2),
    ] {
        // gemm_sub: C (m × n) ← C − A (m × k) Bᵀ (B is n × k).
        let a = dd_block(m, k, &mut rng);
        let b = dd_block(n, k, &mut rng);
        let c = dd_block(m, n, &mut rng);
        let (mut c1, mut c2) = (c.clone(), c);
        DdDense.gemm_sub(&a, &b, &mut c1);
        NaiveDense.gemm_sub(&a, &b, &mut c2);
        assert_eq!(bits(&c1), bits(&c2), "gemm_sub {m} × {k} × {n}");

        // syrk_sub: C (m × m) ← C − A Aᵀ, lower triangle.
        let c = dd_block(m, m, &mut rng);
        let (mut c1, mut c2) = (c.clone(), c.clone());
        DdDense.syrk_sub(&a, &mut c1);
        NaiveDense.syrk_sub(&a, &mut c2);
        assert_eq!(bits(&c1), bits(&c2), "syrk_sub {m} × {k}");
        for j in 0..m {
            for i in 0..j {
                assert_eq!(c1.get(i, j), c.get(i, j), "(D3): upper triangle");
            }
        }

        // trsm_lower, both sides, with L of order k.
        let l = dd_lower(k, &mut rng);
        let x = dd_block(m, k, &mut rng);
        let (mut x1, mut x2) = (x.clone(), x);
        DdDense.trsm_lower(&l, &mut x1, true);
        NaiveDense.trsm_lower(&l, &mut x2, true);
        assert_eq!(bits(&x1), bits(&x2), "trsm_lower (transposed) {m} × {k}");
        let y = dd_block(k, n, &mut rng);
        let (mut y1, mut y2) = (y.clone(), y);
        DdDense.trsm_lower(&l, &mut y1, false);
        NaiveDense.trsm_lower(&l, &mut y2, false);
        assert_eq!(bits(&y1), bits(&y2), "trsm_lower {k} × {n}");

        // potrf and sytrf are NaiveDense's.
        let mut spd = dd_block(k, k, &mut rng);
        for j in 0..k {
            #[allow(clippy::cast_precision_loss)] // small
            spd.set(j, j, Dd::from_f64(k as f64 + 2.0));
        }
        let (mut p1, mut p2) = (spd.clone(), spd.clone());
        assert_eq!(DdDense.potrf(&mut p1), NaiveDense.potrf(&mut p2));
        assert_eq!(bits(&p1), bits(&p2), "potrf {k}");
        let (mut s1, mut s2) = (spd.clone(), spd);
        let (mut q1, mut q2) = (Perm::identity(0), Perm::identity(0));
        let (mut t1, mut t2) = (Vec::new(), Vec::new());
        assert_eq!(
            DdDense.sytrf(&mut s1, &mut q1, &mut t1),
            NaiveDense.sytrf(&mut s2, &mut q2, &mut t2)
        );
        assert_eq!((bits(&s1), q1, t1), (bits(&s2), q2, t2), "sytrf {k}");
    }
    assert_eq!(<DdDense as DenseKernel<Dd>>::name(&DdDense), "dd");
}

