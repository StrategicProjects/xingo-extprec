/// What the `f64` defaults cost in double-double, and what the profile
/// gives back: the accuracy on a random basis (the default drop tolerance
/// caps it at that of `f64`), and matrices that the default absolute pivot
/// tolerance rejects.
#[test]
fn dd_profile_restores_what_the_f64_defaults_lose() {
    // (i) drop_tol: the basis of order 800 of the first test.
    let (n, per_col, seed) = (800, 2, 8);
    let a: CscMatrix<Dd> = to_csc(n, n, &random_entries(n, per_col, seed));
    let heading = structural(n);
    let mut rng = Lcg(seed ^ 0xabcd);
    let b: Vec<Dd> = (0..n).map(|_| Dd::from_f64(rng.unit())).collect();
    let solve = |opts: LuOptions| {
        let mut lu = Lu::<Dd>::new(opts);
        lu.factorize(&a).expect("nonsingular");
        let mut x = SparseVec::from_dense(&b);
        lu.ftran(&mut x);
        let r = basis_residual(&heading, &a, x.values(), &b);
        scaled(&r, &a, x.values(), &b)
    };
    let with_default = solve(LuOptions::default());
    let with_profile = solve(Dd::lu_options());
    assert!(with_profile <= 50.0, "profile: {with_profile:e}");
    assert!(
        with_default >= 1e10,
        "default: {with_default:e} is suspiciously small"
    );

    // (ii) abs_pivot_tol: the Hilbert matrix of order 16.
    let n = 16;
    let mut t = Triplets::new(n, n);
    let mut b = vec![Dd::ZERO; n];
    for (i, bi) in b.iter_mut().enumerate() {
        for j in 0..n {
            #[allow(clippy::cast_precision_loss)] // small integers
            let h = Dd::ONE / Dd::from_f64((i + j + 1) as f64);
            t.push(idx(i), idx(j), h);
            *bi += h;
        }
    }
    let h: CscMatrix<Dd> = t.to_csc().expect("valid triplets");
    let mut lu = Lu::<Dd>::new(LuOptions::default());
    assert!(
        matches!(
            lu.factorize(&h),
            Err(xingo_sparse::LuError::Singular { .. })
        ),
        "the f64 thresholds accept the Hilbert matrix of order 16"
    );
    let mut lu = Lu::<Dd>::new(Dd::lu_options());
    lu.factorize(&h).expect("regular in double-double");
    let mut x = SparseVec::from_dense(&b);
    lu.ftran(&mut x);
    let err = x
        .values()
        .iter()
        .fold(0.0_f64, |m, &v| m.max((v - 1.0).abs().to_f64()));
    assert!(err <= 1e-8, "Hilbert 16: error {err:e}");
}
