//! Integration proof of L2.2a: the factorizations of `xingo-sparse`
//! instantiate in `DoubleDouble` through the public API alone, and solve to
//! double-double accuracy. And of L2.2b (the last group of tests): with the
//! dense kernel `DdDense` they return the bits of the generic kernel.
//!
//! Every check is written once, generic in the scalar `T: Real`, and run in
//! `f64` and in `DoubleDouble` with the same tolerance *in units of
//! `T::EPSILON`* — "the LU instantiated in dd passes the same tests as in
//! f64" (PLAN.md, L2.2). The residuals are computed in `T` itself; a second
//! group of tests measures the `f64` solutions in double-double arithmetic
//! to show the gain.
//!
//! The matrices are generated by a fixed linear congruential generator: no
//! file, no randomness between runs.

use xingo_extprec::{DdDense, DoubleDouble};
use xingo_sparse::{
    Amd, Col, ColumnRef, CscMatrix, DenseBlock, DenseKernel, KktForm, KktSolver, Lu, LuFactor,
    LuOptions, NaiveDense, Perm, Real, Regularization, SparseVec, SupernodalLdl, SupernodalOptions,
    Triplets, UpdateOutcome,
};

/// Knuth's MMIX generator; `unit` is uniform in `[-1, 1)`.
struct Lcg(u64);

impl Lcg {
    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        self.0 >> 11
    }

    #[allow(clippy::cast_precision_loss)] // 53 random bits
    fn unit(&mut self) -> f64 {
        (self.next() as f64) / (1_u64 << 52) as f64 - 1.0
    }

    fn below(&mut self, n: usize) -> usize {
        usize::try_from(self.next() % n as u64).expect("below n")
    }
}

fn idx(i: usize) -> u32 {
    u32::try_from(i).expect("fits u32")
}

/// A sparse nonsingular `n × n` matrix as coordinates: a diagonal of
/// magnitude in `[2, 4)` and `per_col` off-diagonal entries per column in
/// `[-1, 1)` (duplicates are summed by `Triplets`).
fn random_entries(n: usize, per_col: usize, seed: u64) -> Vec<(usize, usize, f64)> {
    let mut rng = Lcg(seed);
    let mut e = Vec::new();
    for j in 0..n {
        let d = 3.0 + rng.unit();
        e.push((j, j, if rng.next().is_multiple_of(2) { d } else { -d }));
        for _ in 0..per_col.min(n - 1) {
            let i = rng.below(n);
            if i != j {
                e.push((i, j, rng.unit()));
            }
        }
    }
    e
}

fn to_csc<T: Real>(n_rows: usize, n_cols: usize, entries: &[(usize, usize, f64)]) -> CscMatrix<T> {
    let mut t = Triplets::new(n_rows, n_cols);
    for &(i, j, v) in entries {
        t.push(idx(i), idx(j), T::from_f64(v));
    }
    t.to_csc().expect("valid triplets")
}

fn norm_inf<T: Real>(v: &[T]) -> T {
    v.iter().fold(T::ZERO, |acc, x| acc.max(x.abs()))
}

/// `max |a_ij|`.
fn max_abs<T: Real>(a: &CscMatrix<T>) -> T {
    (0..a.n_cols()).fold(T::ZERO, |acc, j| {
        acc.max(norm_inf(a.col(Col::from_usize(j)).1))
    })
}

/// `B v − b` for the basis `heading` of `a` (`v` by position, the result
/// by row).
fn basis_residual<T: Real>(heading: &[ColumnRef], a: &CscMatrix<T>, v: &[T], b: &[T]) -> Vec<T> {
    let mut r: Vec<T> = b.iter().map(|&x| -x).collect();
    for (k, c) in heading.iter().enumerate() {
        c.for_each_entry(a, |i, b_ik| r[i as usize] += b_ik * v[k]);
    }
    r
}

/// `Bᵀ w − c` (`w` by row, the result by position).
fn basis_transpose_residual<T: Real>(
    heading: &[ColumnRef],
    a: &CscMatrix<T>,
    w: &[T],
    c: &[T],
) -> Vec<T> {
    heading
        .iter()
        .zip(c)
        .map(|(col, &ck)| {
            let mut s = -ck;
            col.for_each_entry(a, |i, b_ik| s += b_ik * w[i as usize]);
            s
        })
        .collect()
}

/// The options of every test: no entry is dropped (the default drop
/// tolerance, `1e-12`, is an `f64`-scale threshold: it would cap the
/// accuracy of a double-double solve at `1e-12`).
fn options() -> LuOptions {
    LuOptions {
        drop_tol: 0.0,
        ..LuOptions::default()
    }
}

fn structural(n: usize) -> Vec<ColumnRef> {
    (0..n)
        .map(|j| ColumnRef::Structural(Col::from_usize(j)))
        .collect()
}

/// The scaled residual `‖r‖∞ / (n ε_T (max|a| ‖x‖∞ + ‖b‖∞))`, in `f64`.
#[allow(clippy::cast_precision_loss)] // n is small
fn scaled<T: Real>(r: &[T], a: &CscMatrix<T>, x: &[T], b: &[T]) -> f64 {
    let scale = max_abs(a) * norm_inf(x) + norm_inf(b);
    (norm_inf(r) / (T::EPSILON * scale)).to_f64() / r.len() as f64
}

/// Factorize, FTRAN, BTRAN on a random basis; the scaled residuals of both
/// solves (and the invariants of the factor).
fn lu_solves<T: Real>(n: usize, per_col: usize, seed: u64) -> (f64, f64) {
    let a: CscMatrix<T> = to_csc(n, n, &random_entries(n, per_col, seed));
    let heading = structural(n);
    let mut rng = Lcg(seed ^ 0xabcd);
    let b: Vec<T> = (0..n).map(|_| T::from_f64(rng.unit())).collect();

    let mut lu = Lu::<T>::new(options());
    lu.factorize(&a).expect("nonsingular");
    lu.check_invariants().expect("factor invariants");
    assert!(lu.is_valid() && lu.m() == n);

    let mut x = SparseVec::from_dense(&b);
    lu.ftran(&mut x);
    let rx = basis_residual(&heading, &a, x.values(), &b);
    let mut y = SparseVec::from_dense(&b);
    lu.btran(&mut y);
    let ry = basis_transpose_residual(&heading, &a, y.values(), &b);
    (
        scaled(&rx, &a, x.values(), &b),
        scaled(&ry, &a, y.values(), &b),
    )
}

/// The same systems, the same bound in units of `ε_T`, in both scalars.
#[test]
fn lu_passes_the_same_residual_test_in_f64_and_dd() {
    for (n, per_col, seed) in [
        (1, 0, 1),
        (2, 1, 2),
        (5, 2, 3),
        (12, 3, 4),
        (40, 3, 5),
        (120, 4, 6),
        (300, 3, 7),
        (800, 2, 8),
    ] {
        let bound = 50.0;
        let (fx, fy) = lu_solves::<f64>(n, per_col, seed);
        let (dx, dy) = lu_solves::<DoubleDouble>(n, per_col, seed);
        assert!(fx <= bound && fy <= bound, "f64, n = {n}: {fx:e}, {fy:e}");
        assert!(dx <= bound && dy <= bound, "dd, n = {n}: {dx:e}, {dy:e}");
    }
}

/// A double-double solve is some sixteen digits better than an `f64` one,
/// both residuals measured in double-double arithmetic.
#[test]
fn dd_lu_residual_is_far_below_the_f64_one() {
    for (n, per_col, seed) in [(5, 2, 11), (60, 3, 12), (400, 3, 13)] {
        let entries = random_entries(n, per_col, seed);
        let a64: CscMatrix<f64> = to_csc(n, n, &entries);
        let add: CscMatrix<DoubleDouble> = to_csc(n, n, &entries);
        let heading = structural(n);
        let mut rng = Lcg(seed);
        let b64: Vec<f64> = (0..n).map(|_| rng.unit()).collect();
        let bdd: Vec<DoubleDouble> = b64.iter().map(|&v| DoubleDouble::from_f64(v)).collect();

        let mut lu64 = Lu::<f64>::new(options());
        lu64.factorize(&a64).expect("nonsingular");
        let mut x64 = SparseVec::from_dense(&b64);
        lu64.ftran(&mut x64);

        let mut ludd = Lu::<DoubleDouble>::new(options());
        ludd.factorize(&add).expect("nonsingular");
        let mut xdd = SparseVec::from_dense(&bdd);
        ludd.ftran(&mut xdd);
        for v in xdd.values() {
            v.check_invariants().expect("normalized solution");
        }

        // Both residuals in double-double.
        let promoted: Vec<DoubleDouble> = x64
            .values()
            .iter()
            .map(|&v| DoubleDouble::from_f64(v))
            .collect();
        let r64 = norm_inf(&basis_residual(&heading, &add, &promoted, &bdd)).to_f64();
        let rdd = norm_inf(&basis_residual(&heading, &add, xdd.values(), &bdd)).to_f64();
        assert!(rdd <= 1e-26, "n = {n}: dd residual {rdd:e}");
        assert!(
            r64 >= 1e-19,
            "n = {n}: f64 residual {r64:e} is suspiciously small"
        );
        assert!(rdd <= 1e-10 * r64, "n = {n}: {rdd:e} against {r64:e}");
        // And the leading components agree with the f64 solution.
        for (p, q) in x64.values().iter().zip(xdd.values()) {
            assert!(
                (p - q.to_f64()).abs() <= 1e-10 * (1.0 + p.abs()),
                "{p:e} vs {q:?}"
            );
        }
    }
}

/// The Hilbert matrix of order 10 (condition number `1.6 · 10¹³`): the
/// `f64` LU keeps three digits of the solution, the double-double one
/// nineteen.
#[test]
fn hilbert_system_is_solved_to_dd_accuracy() {
    #[allow(clippy::cast_precision_loss)] // small integers
    fn hilbert<T: Real>(n: usize) -> (CscMatrix<T>, Vec<T>) {
        let mut t = Triplets::new(n, n);
        let mut b = vec![T::ZERO; n];
        for (i, bi) in b.iter_mut().enumerate() {
            for j in 0..n {
                let h = T::ONE / T::from_f64((i + j + 1) as f64);
                t.push(idx(i), idx(j), h);
                *bi += h;
            }
        }
        (t.to_csc().expect("valid triplets"), b)
    }
    fn error<T: Real>(n: usize) -> f64 {
        let (a, b) = hilbert::<T>(n);
        let mut lu = Lu::<T>::new(LuOptions {
            abs_pivot_tol: 1e-30,
            drop_tol: 0.0,
            ..LuOptions::default()
        });
        lu.factorize(&a).expect("nonsingular");
        let mut x = SparseVec::from_dense(&b);
        lu.ftran(&mut x);
        // The solution of H x = H·1 is the vector of ones.
        let e: Vec<T> = x.values().iter().map(|&v| v - T::ONE).collect();
        norm_inf(&e).to_f64()
    }
    let e64 = error::<f64>(10);
    let edd = error::<DoubleDouble>(10);
    assert!(edd <= 1e-15, "dd error {edd:e}");
    assert!(e64 >= 1e-8, "f64 error {e64:e} is suspiciously small");
}

/// One Forrest–Tomlin exchange and the solves after it, generic in `T`.
fn exchange<T: Real>(n: usize, seed: u64) -> f64 {
    // n + 1 columns: the basis is the first n, column n enters.
    let mut entries = random_entries(n, 3, seed);
    let mut rng = Lcg(seed ^ 0x55);
    for i in 0..n {
        if i % 3 == 0 {
            entries.push((i, n, 1.0 + rng.unit().abs()));
        }
    }
    let a: CscMatrix<T> = to_csc(n, n + 1, &entries);
    let mut heading = structural(n);
    let mut lu = Lu::<T>::new(options());
    lu.factorize(&(heading.as_slice(), &a))
        .expect("nonsingular");

    let r = n / 2;
    let entering = ColumnRef::Structural(Col::from_usize(n));
    let mut alpha = SparseVec::new(n);
    entering.for_each_entry(&a, |i, v| alpha.set(i, v));
    lu.ftran_for_update(&mut alpha);
    let alpha_r = alpha.get(idx(r));
    let outcome = lu.update(r, alpha_r).expect("a nonsingular exchange");
    heading[r] = entering;
    if outcome != UpdateOutcome::Updated {
        lu.factorize(&(heading.as_slice(), &a))
            .expect("nonsingular");
    }
    lu.check_invariants().expect("factor invariants");

    let b: Vec<T> = (0..n).map(|_| T::from_f64(rng.unit())).collect();
    let mut x = SparseVec::from_dense(&b);
    lu.ftran(&mut x);
    let rx = basis_residual(&heading, &a, x.values(), &b);
    let mut y = SparseVec::from_dense(&b);
    lu.btran(&mut y);
    let ry = basis_transpose_residual(&heading, &a, y.values(), &b);
    scaled(&rx, &a, x.values(), &b).max(scaled(&ry, &a, y.values(), &b))
}

#[test]
fn forrest_tomlin_update_passes_in_f64_and_dd() {
    for (n, seed) in [(6, 21), (30, 22), (150, 23)] {
        let f = exchange::<f64>(n, seed);
        let d = exchange::<DoubleDouble>(n, seed);
        assert!(f <= 1e3, "f64, n = {n}: {f:e}");
        assert!(d <= 1e3, "dd, n = {n}: {d:e}");
    }
}

/// The lower triangle of a sparse symmetric positive definite matrix
/// (strictly diagonally dominant).
fn spd_lower(n: usize, seed: u64) -> Vec<(usize, usize, f64)> {
    let mut rng = Lcg(seed);
    let mut e = Vec::new();
    for j in 0..n {
        e.push((j, j, 8.0 + rng.unit()));
        for _ in 0..2 {
            let i = rng.below(n);
            if i > j {
                e.push((i, j, rng.unit()));
            }
        }
        if j + 1 < n {
            e.push((j + 1, j, rng.unit()));
        }
    }
    e
}

/// `K x − b` for a symmetric `K` given by its lower triangle.
fn symmetric_residual<T: Real>(k_lower: &CscMatrix<T>, x: &[T], b: &[T]) -> Vec<T> {
    let mut r: Vec<T> = b.iter().map(|&v| -v).collect();
    for j in 0..k_lower.n_cols() {
        let (rows, vals) = k_lower.col(Col::from_usize(j));
        for (&i, &v) in rows.iter().zip(vals) {
            let i = i as usize;
            r[i] += v * x[j];
            if i != j {
                r[j] += v * x[i];
            }
        }
    }
    r
}

/// Analyze, factorize (no regularization) and solve with the supernodal
/// LDLᵀ and its default dense kernel; the scaled residual.
fn ldl_solves<T: Real>(n: usize, seed: u64, form: KktForm, entries: &[(usize, usize, f64)]) -> f64 {
    let k: CscMatrix<T> = to_csc(n, n, entries);
    let solver = SupernodalLdl::<T>::default();
    let sym = solver
        .analyze(&k.pattern(), form, &Amd::default())
        .expect("symmetric lower pattern");
    let (num, inertia) = solver
        .factorize(&sym, &k, Regularization::none())
        .expect("factorizable");
    assert_eq!(inertia, form.expected_inertia(n));
    let mut rng = Lcg(seed ^ 0x77);
    let b: Vec<T> = (0..n).map(|_| T::from_f64(rng.unit())).collect();
    let mut x = b.clone();
    solver.solve(&num, &mut x);
    let r = symmetric_residual(&k, &x, &b);
    scaled(&r, &k, &x, &b)
}

#[test]
fn supernodal_ldl_passes_in_f64_and_dd() {
    for (n, seed) in [(1, 31), (4, 32), (25, 33), (150, 34), (500, 35)] {
        let entries = spd_lower(n, seed);
        let form = KktForm::NormalEquations;
        let f = ldl_solves::<f64>(n, seed, form, &entries);
        let d = ldl_solves::<DoubleDouble>(n, seed, form, &entries);
        assert!(f <= 50.0, "f64, n = {n}: {f:e}");
        assert!(d <= 50.0, "dd, n = {n}: {d:e}");
    }
}

/// A quasi-definite augmented system `[−D Aᵀ; A δI]`.
#[test]
fn supernodal_ldl_solves_an_augmented_system_in_dd() {
    let (n_primal, n_dual) = (30, 12);
    let n = n_primal + n_dual;
    let mut rng = Lcg(41);
    let mut entries = Vec::new();
    for j in 0..n_primal {
        entries.push((j, j, -(1.0 + rng.unit().abs())));
    }
    for i in 0..n_dual {
        entries.push((n_primal + i, n_primal + i, 0.5 + rng.unit().abs()));
        for _ in 0..4 {
            entries.push((n_primal + i, rng.below(n_primal), rng.unit()));
        }
    }
    let form = KktForm::Augmented { n_primal, n_dual };
    let f = ldl_solves::<f64>(n, 41, form, &entries);
    let d = ldl_solves::<DoubleDouble>(n, 41, form, &entries);
    assert!(f <= 1e3, "f64: {f:e}");
    assert!(d <= 1e3, "dd: {d:e}");
}

/// The containers are generic too: products and transposes in `T`.
#[test]
fn containers_hold_double_doubles() {
    let third = DoubleDouble::ONE / 3.0;
    let mut t = Triplets::new(2, 2);
    t.push(0, 0, third);
    t.push(1, 0, DoubleDouble::ONE);
    t.push(1, 1, third);
    t.push(1, 1, third); // summed
    let a: CscMatrix<DoubleDouble> = t.to_csc().expect("valid triplets");
    a.check_invariants().expect("csc invariants");
    let two_thirds = third + third;
    assert_eq!(
        a.get(xingo_sparse::Row::from_usize(1), Col::from_usize(1)),
        two_thirds
    );
    // gaxpy: y_i ← y_i + a_ij (α x_j), in double-double.
    let three = DoubleDouble::from_f64(3.0);
    let mut y = vec![DoubleDouble::ZERO; 2];
    a.gaxpy(DoubleDouble::ONE, &[three, DoubleDouble::ONE], &mut y);
    assert_eq!(y[0], third * three);
    assert_eq!(y[1], three + two_thirds);
    assert!((y[0] - 1.0).abs() <= DoubleDouble::EPSILON);
    let csr = a.to_csr();
    csr.check_invariants().expect("csr invariants");
    assert_eq!(a.transpose().transpose(), a);
}

