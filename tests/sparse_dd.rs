/// A matrix as coordinates.
type Entries = Vec<(usize, usize, f64)>;

/// The lower triangle of the five-point Laplacian of a `k × k` grid, plus
/// `shift` on the diagonal: wide supernodes under any fill-reducing order.
fn grid_lower(k: usize, shift: f64) -> Vec<(usize, usize, f64)> {
    let mut e = Vec::new();
    for y in 0..k {
        for x in 0..k {
            let j = x + y * k;
            e.push((j, j, 4.0 + shift));
            if x + 1 < k {
                e.push((j + 1, j, -1.0));
            }
            if y + 1 < k {
                e.push((j + k, j, -1.0));
            }
        }
    }
    e
}

/// Analyze, factorize and solve with the given kernel; the solution, the
/// number of supernodes and whether the factor was pivoted.
fn ldl_with<K: DenseKernel<Dd>>(
    kernel: K,
    opts: SupernodalOptions,
    n: usize,
    form: KktForm,
    entries: &[(usize, usize, f64)],
    reg: Regularization<Dd>,
) -> (Vec<Dd>, usize, bool) {
    let k: CscMatrix<Dd> = to_csc(n, n, entries);
    let solver = SupernodalLdl::<Dd, K>::new(kernel, opts);
    let sym = solver
        .analyze(&k.pattern(), form, &Amd::default())
        .expect("symmetric lower pattern");
    let (num, _) = solver.factorize(&sym, &k, reg).expect("factorizable");
    let mut rng = Lcg(0x5eed ^ n as u64);
    let b: Vec<Dd> = (0..n).map(|_| Dd::from_f64(rng.unit()) / 7.0).collect();
    let mut x = b.clone();
    solver.solve(&num, &mut x);
    let r = symmetric_residual(&k, &x, &b);
    assert!(
        scaled(&r, &k, &x, &b) <= 1e3 || reg != Regularization::none(),
        "residual of the unregularized solve"
    );
    (x, num.n_supernodes(), num.is_pivoted())
}

/// The supernodal factorization with `DdDense` returns the solution of the
/// generic kernel bit for bit: the systems of the tests above, and grids
/// whose supernodes are wide enough for the dense kernels to be called
/// (panels, `trsm`, `gemm`), with `LDLᵀ` (regularized, quasi-definite) and
/// with the pivoted `LBLᵀ` (no regularization).
#[test]
fn supernodal_ldl_with_dd_dense_matches_the_generic_kernel() {
    let default = SupernodalOptions::default();
    // Dense blocks whatever the sparsity, narrow supernodes included.
    let forced = SupernodalOptions {
        supernodal_switch: 0.0,
        min_supernode_cols: 1,
        ..default
    };
    let mut cases: Vec<(String, usize, KktForm, Entries)> = Vec::new();
    for (n, seed) in [(25, 33), (150, 34), (500, 35)] {
        cases.push((
            format!("spd {n}"),
            n,
            KktForm::NormalEquations,
            spd_lower(n, seed),
        ));
    }
    for g in [6, 17, 30] {
        cases.push((
            format!("grid {g}"),
            g * g,
            KktForm::NormalEquations,
            grid_lower(g, 0.25),
        ));
    }
    // A quasi-definite augmented system on a grid-like coupling.
    let (n_primal, n_dual) = (120, 60);
    let mut rng = Lcg(43);
    let mut aug = Vec::new();
    for j in 0..n_primal {
        aug.push((j, j, -(1.0 + rng.unit().abs())));
    }
    for i in 0..n_dual {
        aug.push((n_primal + i, n_primal + i, 0.5 + rng.unit().abs()));
        for d in 0..6 {
            aug.push((n_primal + i, (2 * i + d) % n_primal, rng.unit()));
        }
    }
    cases.push((
        "augmented".to_string(),
        n_primal + n_dual,
        KktForm::Augmented { n_primal, n_dual },
        aug,
    ));

    let mut wide = 0;
    for (label, n, form, entries) in &cases {
        for (o, opts) in [default, forced].into_iter().enumerate() {
            for reg in [Regularization::none(), Regularization::default()] {
                let (x, sn, pivoted) = ldl_with(DdDense, opts, *n, *form, entries, reg);
                let (y, sn0, pivoted0) = ldl_with(NaiveDense, opts, *n, *form, entries, reg);
                assert_eq!((sn, pivoted), (sn0, pivoted0), "{label}, options {o}");
                assert!(
                    x.iter()
                        .zip(&y)
                        .all(|(p, q)| p.hi().to_bits() == q.hi().to_bits()
                            && p.lo().to_bits() == q.lo().to_bits()),
                    "{label}, options {o}: DdDense and NaiveDense disagree"
                );
                for v in &x {
                    v.check_invariants().expect("normalized solution");
                }
                if sn < *n {
                    wide += 1;
                }
            }
        }
    }
    // The dense kernels were exercised: some factorizations had supernodes
    // of more than one column.
    assert!(wide >= 8, "{wide} factorizations with wide supernodes");
}

